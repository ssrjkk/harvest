class TestSendTransfer(unittest.IsolatedAsyncioTestCase):
    def _net(self):
        with mock.patch.object(NetworkManager, "_connect_rpc", lambda self, u: mock.MagicMock()):
            net = NetworkManager(_ncfg(["https://a.example/rpc"]), mock.MagicMock())
        acc = mock.MagicMock()
        from web3 import Web3

        acc.address = Web3.to_checksum_address("0x" + "aa" * 20)
        signed = mock.MagicMock()
        signed.raw_transaction = b"rawtx"
        acc.sign_transaction.return_value = signed
        net.get_account = mock.MagicMock(return_value=acc)
        net.w3 = mock.MagicMock()
        net.w3.to_wei = lambda v, u: 1000
        net.claim_nonce = mock.AsyncMock(return_value=7)
        net.get_gas_price = mock.AsyncMock(return_value=10)
        net.get_fee_basis = mock.AsyncMock(return_value=None)
        net.send_raw_transaction = mock.AsyncMock(return_value=b"\xaa" * 32)
        net.invalidate_balance = mock.MagicMock()
        net.release_nonce = mock.AsyncMock()
        net.rollback_nonce_if_free = mock.AsyncMock()
        return net, acc

    async def test_success(self):
        net, acc = self._net()
        net.wait_for_receipt = mock.AsyncMock(return_value={"status": 1})
        net._crosscheck_receipt_status = mock.AsyncMock(return_value=1)
        out = await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1)
        self.assertEqual(out, (b"\xaa" * 32).hex())
        await net.close()

    async def test_success_with_fee_and_data(self):
        net, acc = self._net()
        net.get_fee_basis = mock.AsyncMock(
            return_value={"maxFeePerGas": 5, "maxPriorityFeePerGas": 1}
        )
        net.wait_for_receipt = mock.AsyncMock(return_value={"status": 1})
        net._crosscheck_receipt_status = mock.AsyncMock(return_value=1)
        out = await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1, data_hex="0x1234")
        self.assertEqual(out, (b"\xaa" * 32).hex())
        await net.close()

    async def test_unconfirmed(self):
        net, acc = self._net()
        net.wait_for_receipt = mock.AsyncMock(return_value=None)
        self.assertIsNone(await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1))
        self.assertTrue(net.invalidate_balance.called)
        await net.close()

    async def test_reverted(self):
        net, acc = self._net()
        net.wait_for_receipt = mock.AsyncMock(return_value={"status": 0})
        net._crosscheck_receipt_status = mock.AsyncMock(return_value=0)
        self.assertIsNone(await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1))
        self.assertTrue(net.release_nonce.called)
        await net.close()

    async def test_cancel_before_send_rollbacks(self):
        net, acc = self._net()
        # отмена после выдачи nonce, но до broadcast — nonce возвращается
        net.get_gas_price = mock.AsyncMock(side_effect=asyncio.CancelledError())
        with self.assertRaises(asyncio.CancelledError):
            await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1)
        self.assertTrue(net.rollback_nonce_if_free.called)
        await net.close()

    async def test_cancel_rollback_failure_swallowed(self):
        net, acc = self._net()
        net.get_gas_price = mock.AsyncMock(side_effect=asyncio.CancelledError())
        net.rollback_nonce_if_free = mock.AsyncMock(side_effect=RuntimeError("rb down"))
        with self.assertRaises(asyncio.CancelledError):
            await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1)
        await net.close()

    async def test_error_rollback_failure_swallowed(self):
        net, acc = self._net()
        net.send_raw_transaction = mock.AsyncMock(side_effect=RuntimeError("send boom"))
        net.rollback_nonce_if_free = mock.AsyncMock(side_effect=RuntimeError("rb down"))
        self.assertIsNone(await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1))
        await net.close()

    async def test_cancel_during_claim_no_rollback(self):
        net, acc = self._net()
        # отмена во время claim_nonce: nonce не выдан — откатывать нечего
        net.claim_nonce = mock.AsyncMock(side_effect=asyncio.CancelledError())
        with self.assertRaises(asyncio.CancelledError):
            await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1)
        self.assertFalse(net.rollback_nonce_if_free.called)
        await net.close()

    async def test_cancel_after_send_no_rollback(self):
        net, acc = self._net()
        net.wait_for_receipt = mock.AsyncMock(side_effect=asyncio.CancelledError())
        with self.assertRaises(asyncio.CancelledError):
            await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1)
        self.assertFalse(net.rollback_nonce_if_free.called)
        await net.close()

    async def test_cancel_no_account(self):
        net, acc = self._net()
        net.get_account = mock.MagicMock(side_effect=asyncio.CancelledError())
        with self.assertRaises(asyncio.CancelledError):
            await net.send_transfer("0xkey", "0x" + "bb" * 20, 0.1)
        await net.close()


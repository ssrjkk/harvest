class _FCur:
    """Awaitable + async-context курсор для подмены aiosqlite/asyncpg."""

    def __init__(self, row=None, rows=None, exc=None):
        self._row = row
        self._rows = rows
        self._exc = exc

    def __await__(self):
        async def _r():
            if self._exc:
                raise self._exc
            return self

        return _r().__await__()

    async def __aenter__(self):
        if self._exc:
            raise self._exc
        return self

    async def __aexit__(self, *a):
        return False

    async def fetchone(self):
        return self._row

    async def fetchall(self):
        return list(self._rows) if self._rows is not None else []


class _FDb:
    def __init__(self, fn):
        self._fn = fn
        self.commits = 0
        self.many = []

    def execute(self, sql, params=()):
        return self._fn(sql, params)

    async def executemany(self, sql, seq):
        self.many.append((sql, list(seq)))

    async def commit(self):
        self.commits += 1

    async def close(self):
        pass


class FakePGConn:
    def __init__(self, rows=None, fail_close=False):
        self.rows = rows if rows is not None else [{"a": 1}]
        self.executed = []
        self.many = []
        self.fail_close = fail_close

    async def fetch(self, sql, *p):
        self.executed.append((sql, p))
        return self.rows

    async def execute(self, sql, *p):
        self.executed.append((sql, p))
        return "OK"

    async def executemany(self, sql, seq):
        self.many.append((sql, list(seq)))

    async def close(self):
        if self.fail_close:
            raise RuntimeError("close boom")


class TestTranslatePg(unittest.TestCase):
    def test_noop(self):
        self.assertEqual(_translate_pg("PRAGMA journal_mode=WAL"), ("-- pg no-op", ()))
        self.assertEqual(_translate_pg("  vacuum  "), ("-- pg no-op", ()))

    def test_datetime_and_autoincrement(self):
        out, _ = _translate_pg("SELECT datetime('now')")
        self.assertIn("now()", out)
        out, _ = _translate_pg('SELECT datetime("now")')
        self.assertIn("now()", out)
        out, _ = _translate_pg("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT)")
        self.assertIn("GENERATED BY DEFAULT AS IDENTITY", out)

    def test_replace_valid_cols(self):
        out, _ = _translate_pg("INSERT OR REPLACE INTO wallets (address, private_key) VALUES (?, ?)")
        self.assertNotIn("OR REPLACE", out)
        self.assertIn("$1", out)
        self.assertIn("$2", out)
        self.assertIn("ON CONFLICT(address)", out)

    def test_replace_invalid_cols(self):
        out, _ = _translate_pg("INSERT OR REPLACE INTO t (123bad, foo-bar) VALUES (?, ?)")
        self.assertIn("ON CONFLICT DO NOTHING", out)

    def test_replace_no_cols(self):
        out, _ = _translate_pg("INSERT OR REPLACE INTO wallets VALUES (?, ?)")
        self.assertIn("ON CONFLICT DO NOTHING", out)

    def test_replace_existing_conflict_untouched(self):
        sql = "INSERT OR REPLACE INTO t (a) VALUES (?) ON CONFLICT(a) DO NOTHING"
        out, _ = _translate_pg(sql)
        self.assertEqual(out.count("ON CONFLICT"), 1)

    def test_ignore(self):
        out, _ = _translate_pg("INSERT OR IGNORE INTO t (a) VALUES (?)")
        self.assertIn("ON CONFLICT DO NOTHING", out)

    def test_plain_insert_no_suffix(self):
        out, _ = _translate_pg("INSERT INTO t (a) VALUES (?)")
        self.assertIn("$1", out)
        self.assertNotIn("ON CONFLICT", out)

    def test_plain_insert_existing_conflict(self):
        sql = "INSERT INTO t (a) VALUES (?) ON CONFLICT(a) DO NOTHING"
        out, _ = _translate_pg(sql)
        self.assertEqual(out.count("ON CONFLICT"), 1)

    def test_placeholders_skip_literals(self):
        out, _ = _translate_pg("SELECT '?' , ?")
        self.assertIn("'?'", out)
        self.assertIn("$1", out)
        out, _ = _translate_pg('SELECT "?" , ?')
        self.assertIn('"?"', out)
        self.assertIn("$1", out)

    def test_escaped_quote_literal(self):
        out, _ = _translate_pg("SELECT 'it''s ?' , ?")
        self.assertIn("'it''s ?'", out)
        self.assertIn("$1", out)

    def test_params_passthrough(self):
        out, p = _translate_pg("SELECT ?", ("x",))
        self.assertEqual(p, ("x",))
        self.assertIn("$1", out)


